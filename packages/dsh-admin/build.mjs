/*
 * Build client.js: the shared workbench (packages/admin-ui) plus the panel
 * registration in src/client.jsx, as one file the Harness module loader runs.
 * React is the Harness's own copy, handed in through the loader's `require`.
 *
 *   node packages/dsh-admin/build.mjs
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// esbuild is not a direct dependency; use the copy Astro's toolchain installs.
const fromRoot = createRequire(join(here, '../../package.json'));
const { build } = createRequire(fromRoot.resolve('astro/package.json'))('esbuild');
const HOOKS = ['createContext', 'createElement', 'Fragment', 'useCallback', 'useContext', 'useEffect', 'useMemo', 'useRef', 'useState', 'useSyncExternalStore'];

const hostReact = {
  name: 'host-react',
  setup(b) {
    b.onResolve({ filter: /^react(\/jsx-runtime)?$/ }, (args) => ({ path: args.path, namespace: 'host-react' }));
    b.onLoad({ filter: /.*/, namespace: 'host-react' }, (args) => ({
      loader: 'js',
      contents:
        args.path === 'react'
          ? `const R = globalThis.__AW_REACT__; export default R; export const { ${HOOKS.join(', ')} } = R;`
          : `const R = globalThis.__AW_REACT__; export const Fragment = R.Fragment;
             export function jsx(type, props, key) { return R.createElement(type, key === undefined ? props : { ...props, key }); }
             // Static children arrive as one array; spread them so React does not ask for keys.
             export function jsxs(type, props, key) {
               const { children, ...rest } = props;
               return R.createElement(type, key === undefined ? rest : { ...rest, key }, ...children);
             }`,
    }));
  },
};

const out = await build({
  entryPoints: [join(here, 'src/client.jsx')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: '__awPlugin',
  jsx: 'automatic',
  target: 'es2022',
  legalComments: 'none',
  plugins: [hostReact],
});

const banner = `/* Generated by build.mjs from src/client.jsx and packages/admin-ui. Do not edit. */\n`;
const code = `${banner}window.__ModuleLoader__.load({
  id: '@malipetek/dsh-admin',
  factory(require) {
    globalThis.__AW_REACT__ = require('react');
${out.outputFiles[0].text}
    return __awPlugin.default;
  },
});
`;
writeFileSync(join(here, 'client.js'), code);
console.log(`client.js: ${(code.length / 1024).toFixed(1)} KiB`);
