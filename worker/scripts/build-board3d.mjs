/*
 * Build src/board3dBundle.ts: the portal's 3D board (initBoard in
 * ../src/lib/workshop3d.ts, three.js included) as one minified script, for the
 * plugin card (src/boardUi.ts). The card's iframe has no network access, so
 * the scene has to travel inside its HTML. Rerun after workshop3d.ts changes:
 *
 *   node scripts/build-board3d.mjs
 *
 * The bundle is written as a JSON string literal, because minified three.js is
 * full of backticks and `${` that a template literal would mangle.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
// esbuild is not a direct dependency; use the copy Astro's toolchain installs (as packages/dsh-admin does).
const fromRoot = createRequire(join(root, 'package.json'));
const { build } = createRequire(fromRoot.resolve('astro/package.json'))('esbuild');

const out = await build({
  stdin: {
    contents: "import { initBoard } from './src/lib/workshop3d.ts';\nwindow.mkInitBoard = initBoard;\n",
    resolveDir: root,
    loader: 'ts',
    sourcefile: 'board3d-entry.ts',
  },
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});
const code = out.outputFiles[0].text;
// Inside an inline <script>, "</script" would end the element early.
if (/<\/script/i.test(code)) throw new Error('bundle contains </script');

writeFileSync(
  join(here, '../src/board3dBundle.ts'),
  `// Generated by scripts/build-board3d.mjs from src/lib/workshop3d.ts. Do not edit.\n` +
    `// eslint-disable-next-line\nexport const BOARD3D_JS: string = ${JSON.stringify(code)};\n`,
);
console.log(`src/board3dBundle.ts: ${(code.length / 1024).toFixed(1)} KiB`);
