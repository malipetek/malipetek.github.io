/**
 * What a locale needs: keys missing or translated from older English (stale),
 * and keys English no longer has (removed). `meta` remembers the English each
 * key was translated from.
 */
export function catalogWork(english, catalog, meta) {
  return {
    stale: Object.keys(english).filter((k) => catalog[k] === undefined || meta[k]?.en !== english[k]),
    removed: Object.keys(catalog).filter((k) => english[k] === undefined),
  };
}

/**
 * Take a model's answer for `keys` into the catalog. A value that is empty or
 * changes the {variables} or plural shape is rejected and the key stays as it
 * was (English shows through the fallback chain). Mutates catalog and meta.
 */
export function acceptTranslations(english, catalog, meta, keys, out) {
  const written = [];
  const rejected = [];
  for (const k of keys) {
    const value = out?.[k];
    if (typeof value !== 'string' || !value.trim() || shape(value) !== shape(english[k])) {
      rejected.push(k);
      continue;
    }
    catalog[k] = value;
    meta[k] = { en: english[k], reviewed: false };
    written.push(k);
  }
  return { written, rejected };
}

/** Drop removed keys and put the rest in English's order: the file as it is written back. */
export function orderedCatalog(english, catalog, meta, removed) {
  for (const k of removed) {
    delete catalog[k];
    delete meta[k];
  }
  return Object.fromEntries(Object.keys(english).filter((k) => catalog[k] !== undefined).map((k) => [k, catalog[k]]));
}

/** A catalog or meta file's text, exactly as the script writes it. */
export const jsonFile = (data) => `${JSON.stringify(data, null, 2)}\n`;

/** src/i18n/mail.js from every locale's catalog ({ code: catalog }, in LOCALES order). */
export function mailBundleSource(catalogs) {
  const bundle = {};
  for (const [code, catalog] of Object.entries(catalogs)) {
    bundle[code] = Object.fromEntries(Object.entries(catalog).filter(([k]) => MAIL_PREFIXES.some((p) => k.startsWith(p))));
  }
  return `// Generated by scripts/i18n-sync.mjs from src/i18n/messages/*.json. Do not edit.\nexport default ${JSON.stringify(bundle, null, 2)};\n`;
}
